import * as assetsModel from './assets.model.js';

export const fetchDigitalTwinData = async (assetId, { captureId, targetDate }) => {
  const asset = await assetsModel.getAssetWithSiteDetails(assetId);
  const activeIssue = await assetsModel.getActiveTicketForAsset(assetId);
  if (!asset) {
    throw new Error('ASSET_NOT_FOUND');
  }

  const timeline = await assetsModel.getCapturesTimeline(assetId);
  const activeCapture = await assetsModel.getTargetCapture(assetId, captureId, targetDate);
  const totalSiteAssets = await assetsModel.countSiteAssets(asset.site_id);

  // If the playground has 5 assets total, this asset's 360 view can point to at most 4 OTHER assets
  const expectedHotspotsCount = Math.max(0, totalSiteAssets - 1);

  let hotspots = [];
  let warningStatus = null;

  if (activeCapture) {
    const rawHotspots = await assetsModel.getHotspotsByCaptureId(activeCapture.id);
    hotspots = rawHotspots.map(h => ({
      id: h.id,
      targetAssetId: h.target_asset_id,
      targetAssetName: h.target_asset_name,
      targetAssetCategory: h.target_asset_category,
      targetAssetStatus: h.target_asset_status,
      pitch: parseFloat(h.pitch),
      yaw: parseFloat(h.yaw),
      isAutoGenerated: h.is_auto_generated
    }));

    const linkedCount = hotspots.length;
    const isMissingHotspots = linkedCount < expectedHotspotsCount;

    warningStatus = {
      totalSiteAssets,
      expectedOtherAssets: expectedHotspotsCount,
      linkedHotspotsCount: linkedCount,
      hasMissingHotspots: isMissingHotspots,
      isWarningIgnored: activeCapture.ignore_hotspot_warning,
      // Only pop up the UI warning if hotspots are missing AND the worker hasn't ignored it
      shouldShowWarning: isMissingHotspots && !activeCapture.ignore_hotspot_warning,
      message: isMissingHotspots
        ? `This 360° image only has ${linkedCount} out of ${expectedHotspotsCount} neighboring assets linked as hotspots.`
        : 'All neighboring site assets are linked.'
    };
  }

  return {
    site: {
      id: asset.site_id,
      code: asset.site_code,
      name: asset.site_name,
      location: asset.site_location,
      latestCapturedAt: timeline[0]?.captured_at || null
    },
    asset: {
      id: asset.id,
      name: asset.name,
      category: asset.category,
      material: asset.material,
      surface: asset.surface_type,
      status: asset.status,
      thumbnailUrl: asset.image_url,
      lat: parseFloat(asset.latitude),
      lng: parseFloat(asset.longitude)
    },
    activeCapture: activeCapture
      ? {
          id: activeCapture.id,
          image360Url: activeCapture.image_360_url,
          capturedAt: activeCapture.captured_at,
          isLatest: activeCapture.is_latest,
          hotspots,
          hotspotValidation: warningStatus
        }
      : null,
    activeIssue: activeIssue
      ? {
          ticketId: activeIssue.id,
          ticketNumber: activeIssue.ticket_number,
          category: activeIssue.category,
          priority: activeIssue.priority,
          description: activeIssue.description,
          status: activeIssue.status,
          reportedOn: activeIssue.created_at
        }
      : null,
    timeline: timeline.map(t => ({
      captureId: t.id,
      capturedAt: t.captured_at,
      isLatest: t.is_latest
    }))
  };
};

export const addOrUpdateHotspot = async (captureId, { targetAssetId, pitch, yaw, userId }) => {
  const sourceCapture = await assetsModel.getCaptureById(captureId);
  if (!sourceCapture) {
    throw new Error('CAPTURE_NOT_FOUND');
  }

  if (sourceCapture.asset_id === targetAssetId) {
    throw new Error('CANNOT_LINK_SELF');
  }

  const targetAsset = await assetsModel.getAssetWithSiteDetails(targetAssetId);
  if (!targetAsset) {
    throw new Error('TARGET_ASSET_NOT_FOUND');
  }

  if (targetAsset.site_id !== sourceCapture.site_id) {
    throw new Error('CROSS_SITE_HOTSPOT_NOT_ALLOWED');
  }

  return await assetsModel.upsertHotspot(captureId, targetAssetId, pitch, yaw, userId, false);
};