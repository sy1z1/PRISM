import { pool } from '../../config/db.js';

// 1. Fetch Asset & Site Metadata (populates the left sidebar)
export const getAssetWithSiteDetails = async (assetId) => {
  const query = `
    SELECT 
      a.id,
      a.name_identifier AS name,
      c.name AS category,
      a.material,
      a.surface_type,
      a.latitude,
      a.longitude,
      a.status,
      a.image_url,
      a.installation_date,
      s.id AS site_id,
      s.site_code,
      s.name AS site_name,
      s.address_location AS site_location
    FROM assets a
    JOIN asset_categories c ON a.category_id = c.id
    JOIN sites s ON a.site_id = s.id
    WHERE a.id = $1;
  `;
  const { rows } = await pool.query(query, [assetId]);
  return rows[0];
};

// 2. Get all captures for an asset (populates the "Captured On" timeline dropdown & slider)
export const getCapturesTimeline = async (assetId) => {
  const query = `
    SELECT id, image_360_url, captured_at, is_latest, ignore_hotspot_warning
    FROM asset_captures
    WHERE asset_id = $1
    ORDER BY captured_at DESC;
  `;
  const { rows } = await pool.query(query, [assetId]);
  return rows;
};

// 3. Time-Machine Query: Get specific capture, closest to targetDate, or latest
export const getTargetCapture = async (assetId, captureId = null, targetDate = null) => {
  if (captureId) {
    const query = `SELECT * FROM asset_captures WHERE id = $1 AND asset_id = $2;`;
    const { rows } = await pool.query(query, [captureId, assetId]);
    return rows[0];
  }

  if (targetDate) {
    // Finds the 360 image captured closest in time to the slider's targetDate
    const query = `
      SELECT *
      FROM asset_captures
      WHERE asset_id = $1
      ORDER BY ABS(EXTRACT(EPOCH FROM (captured_at - $2::timestamptz))) ASC
      LIMIT 1;
    `;
    const { rows } = await pool.query(query, [assetId, targetDate]);
    return rows[0];
  }

  // Default: Return the latest capture
  const query = `
    SELECT *
    FROM asset_captures
    WHERE asset_id = $1
    ORDER BY is_latest DESC, captured_at DESC
    LIMIT 1;
  `;
  const { rows } = await pool.query(query, [assetId]);
  return rows[0];
};

// 4. Get all green hotspots anchored to a specific 360 capture
export const getHotspotsByCaptureId = async (captureId) => {
  const query = `
    SELECT 
      h.id,
      h.target_asset_id,
      a.name_identifier AS target_asset_name,
      c.name AS target_asset_category,
      a.status AS target_asset_status,
      h.pitch,
      h.yaw,
      h.is_auto_generated
    FROM capture_hotspots h
    JOIN assets a ON h.target_asset_id = a.id
    JOIN asset_categories c ON a.category_id = c.id
    WHERE h.source_capture_id = $1;
  `;
  const { rows } = await pool.query(query, [captureId]);
  return rows;
};

